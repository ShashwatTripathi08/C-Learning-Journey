#include<stdio.h>

int main(){
    // int a;
    // a = 1; is same as
    int a = 1;

    // float b = 1.4; is same as 
    float b;
    b = 1.4;

    // char c = 'a'; is same as 
    char c;
    c = 'a'; // char should always be in a single quote.

    printf("The value of a is %d", a);
    printf("The value of b is %f", b);
    printf("The value of c is %c", c);

}

// int: 4 bytes = 32 bits
// float: 4 bytes = 32 bits
// char: 1 byte = 8 bits
// 1 byte = 8 bits

